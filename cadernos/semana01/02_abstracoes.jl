md"""
## Um primeiro encontro com a abstração

Agora, vamos ver como trabalhar com uma coleção de uns, no caso uma matriz de uns, sem que o código precise saber qual o tipo específico dos _uns_ que ela armazena. Ou seja, queremos escrever uma função que recebe a coleção e modifica a matriz em uma posição específica, mas que não está a priori "consciente" de qual é o tipo que ela manipula. 
"""

# ╔═╡ 19f4ddb0-ec44-11ea-20b9-5d97fb2b1cf4
function insert(new, A, i, j)
    B = copy(A)
    B[i, j] = new
    return B
end

