# ╔═╡ db49fa78-756c-45d6-adca-be59bf93e086
md"""
Somando essas aproximações de derivada segunda teremos:

$$f_N + f_S + f_W + f_E - 4f,$$

que é familiar! Nesse sentido o sistema de resistores que vimos acima parece querer aproximar as derivadas segundas do potencial elétrico. De fato terei um pouco a mais para falar sobre isso mais adiante.

Outro fato é que as aproximações de derivada que usamos acima fazem sentido se os deslocamento são unitários, como sugerido pelos pontos. Mas se quisermos usar um deslocamento menor, digamos $h$, as primeiras diferenças deveriam ser divididas por h. Já as segundas diferenças seriam divididas por $h$ novamente. Isso resultaria na fórmula

$$\frac{f(x + h, y) + f(x - h, y) + f(x, y + h) + f(x, y - h) - 4f(x, y)}{h^2}$$

Isso sugere que o circuito elétrico está aproximando somas das derivadas segundas nas direções coordenadas. 

Se tomarmos o limite da expressão acima para $h \rightarrow 0$, obtemos

$$\nabla^2 f = \frac{\partial^2 f}{\partial x^2} + \frac{\partial^2 f}{\partial y^2}
\approx \frac{f(x + h, y) + f(x - h, y) + f(x, y + h) + f(x, y - h) - 4f(x, y)}{h^2}.$$

O operador $\nabla^2 f$ é conhecido como **laplaciano de $f$**.
"""

# ╔═╡ e69d3973-c8ad-4a97-99a9-6b6cd4c6b844
md"""
Assim, o problema de encontrar os potenciais no circuito elétrico passa a ser um caso particular da equação de Poisson:

Dado uma região no plano/espaço $R$ e $g$ definida em $R$, encontrar $f$ definida em $R$ tal que 

$$\nabla^2 f = g,\ \ \text{em que } f \text{ é conhecida apenas na fronteira de } R.$$

Como vimos, essa uma versão contínua do problema de encontrar os valores de $f$ em nós de uma malha para os quais nós conhecemos tantas equações quantos pontos da malha

$$\frac{f(x + h, y) + f(x - h, y) + f(x, y + h) + f(x, y - h) - 4f(x, y)}{h^2} = g(x, y).$$

Como há tantas equações lineares quantos pontos na malha o problema pode ser resolvido resolvendo sistemas lineares. Assim temos uma forma natural de resolver a versão discretizada do problema de Poisson, baseada na ideia de aproximações de derivadas por diferenças finitas.
"""

# ╔═╡ a024fa7a-89ac-4278-8a1a-6d8453cae9ed
load("regiao_R.png")

# ╔═╡ 106dbdde-f9cd-4562-af70-8a9f5c32b818
md"""
Agora, nesse processo de solução é fundamental a operação de aplicar uma máscara sobre uma malha de pontos e fazer uma média dos valores encontrados. Já vimos operações assim, os filtros de convolução. 

No contexto de resolução numérica de equações diferenciais (parciais) essas máscaras são chamadas de estênceis  (em referência às máscaras que usamos para desenhar padrões pré-definidos como letras). Vamos ver como implementá-los em Julia.

Um dos pontos fundamentais desse tipo de operação é como lidar com a **fronteira**. Dependendo do problema que queremos resolver, haverá diferentes condições de fronteira: nula, periódica, derivada nula, etc. O mesmo problema de fronteira ocorria com os filtros de convolação, lembra?

Uma das técnicas mais comuns para lidar com as condições de fronteira é criar uma borda de valores na malha que são configurados para obter o efeito desejado. Esses valores extras são conhecidos como células (ou nós) fantasmas. 

Agora, chega de conversa, vamos ver um pouco de código.
"""


