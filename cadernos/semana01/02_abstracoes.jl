md"""
Antes mesmo de rodar os exemplo, apenas lendo o código, já vem a dúvida: como isso roda? Essa dúvida deve ser particularmente forte para programadores de linguagens fortemente tipadas como C, C++ ou Fortran. Em Julia, e outras linguagens dinâmicas, o código não parece se preocupar com qual é o _um_ que estou colocando na matriz! Ele simplesmente cria uma matriz do tipo adequado.

E sim, é exatamente essa a força da abstração. Para o tipo de operações que estamos fazendo não há motivo para diferenciar entre os diferentes tipos _específicos_ de _um_. A linguagem é "esperta", ou "ágil", o suficiente para criar a matriz do tipo natural desejado e continuar em frente.

Note ainda que a informação que Julia devolve é bastante completa. Veja quais seriam as primeiras linhas (que informam o tipo dos elementos armazenados na matriz) para alguns diferentes _uns_:

```
array = 3x4 Matrix{Int64}
array = 3x4 Matrix{Float64}
array = 3x4 Matrix{Rational{Int64}}
```

Atente que todos esse tem a mesma forma geral: `3x4 Matrix{T}`, em que `T` é o tipo dos elementos colocados na matriz.

Obs: Lembre que `Matrix{T}` é um apelido para `Array{T, 2}`. 
"""

