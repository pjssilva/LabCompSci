# ╔═╡ babe3c24-2901-11eb-2d30-51256eb97e11
[A[i.+neighborhood] for i ∈ I]

# ╔═╡ 7bd3671d-e59d-4d04-a60c-4524b2057972
md"""
# Estêncil

Estamos prontos para aplicar o estêncil (ou um filtro de convolução) em um único passo.
"""

# ╔═╡ e6bd9dea-2901-11eb-1100-ad10705f41cc
estencil = [0 -1 0
    -1 4 -1
    0 -1 0]

# ╔═╡ fe4f6df0-2901-11eb-1945-27e3f041ed1f
[sum(A[i.+neighborhood] .* estencil) for i ∈ I]

# ╔═╡ 48374720-6c79-4c2b-8b81-86565cbf19a2
md"""
Observe que o resultado final tem o mesmo tamanho que os dados originais armazenados em `data`, já que ao aplicar o estêncil aproveitamos a presença das células fantasmas e não foi necessária um tratamento especial para as bordas durante a aplicação do estêncil. 
"""

# ╔═╡ a7615570-0826-4ef1-80b2-da21c0c640b6
md"""
# Outras condições de fronteira

No exemplo acima, preparamos as células fantasmas para ter o efeito de condições de fronteira nula. Mas como lidar com outras condições, como fronteira periódica ou de derivada 0?
"""

# ╔═╡ b596c469-36d4-4517-a6da-5468033cc0a8
A

