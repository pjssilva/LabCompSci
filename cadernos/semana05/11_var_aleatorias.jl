Note que a medida que o número de dados aumenta a distribuição da soma vai ficando "cada vez mais _contínua_". De fato a probabilidade de valores específicos vão diminuindo e é mais interessante consdierá-los em _bins_. Lembrando a aula de estatística, passa a fazer sentido falar na **função densidade da distribuição** e as probabilidades passam a fazer sentido para ver se o valor cai num intervalor $[a, b]$ e não mais num valor específico.
"""

