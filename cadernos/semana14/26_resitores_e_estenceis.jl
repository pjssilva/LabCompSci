begin
    B = copy(A)

    B[0, :] = B[6, :]  ## periodic
    B[7, :] = B[1, :]
    B[:, 0] = B[:, 7]
    B[:, 8] = B[:, 1]
    # The corner values are not important. They are multiplied by 0 in the estêncil.

    # B[0,:] = B[1,:]  ## zero derivative
    # B[7,:] = B[6,:]
    # B[:,0] = B[:,1]
    # B[:,8] = B[:,7]

    B
end

# ╔═╡ 4f342744-2902-11eb-1401-55e770d9d751

for i ∈ I
    B[i] = sum(A[i.+neighborhood] .* estencil)
end


