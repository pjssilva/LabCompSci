# ╔═╡ b5251f76-873c-11eb-38cb-7db300c8fe3c
histogram(
    chisq_data;
    norm=true,
    bins=100,
    size=(500, 300),
    leg=false,
    alpha=0.5,
    xlims=(0, 10 * √(dof)),
)

