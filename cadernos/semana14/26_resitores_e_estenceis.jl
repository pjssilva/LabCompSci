# ╔═╡ 05a4d868-c89f-4ea9-9e64-90f272cd002b
md"""
Resistores são eexmplos simples de componentes elétricos. Eles são colocados no meio de circuitos e oferecem uma resistência, daí o nome, à passagem de corrente. O seu comportamento no circuito é explicado pela [lei de Ohm](https://pt.wikipedia.org/wiki/Lei_de_Ohm):
```math
V = Ri,
```
em que $V$ representa a diferença de potencial elétrico,  $R$ a resistência e $i$ a corrente.

Assim, se ligamos os polos de uma pilha de 9 V nos extremos de um resistor de 1 Ohm veremos a passagem de uma corrente de 9 A.
"""

# ╔═╡ c20402b6-6bd0-4cf3-8487-e046b94d3f31
md"""
A coisa fica bem mais interessante quando combinamos vários resistores em circuitos com padrões complexos. Com o objetivo de motivar a equação de Poisson e o operador laplaciano, vamos considerar um circuito com quatro resistores de 1 Ohm formando um sinal de mais.
"""

# ╔═╡ 2e88b5e6-ba83-4641-8059-acae51c25fa8
load("circuito_mais.png")

# ╔═╡ 02f40dcc-a687-463d-aaea-f052c34ccaec
md"""
Se soubermos as voltagens em todos os pontos do circuito, indicadas acima, podemos usar a lei de Ohm para calcular a correte que sairia do ponto central, que tem uma fórmula simples já que os resistores são de 1 Ohm.
```math
\begin{align*}
\rm{Corrente\ de\ saída} &= (V_N - V) + (V_L - V) + (V_S - V) + (V_O - V) \\
&= (V_N + V_L + V_S + V_O) - 4V.
\end{align*}
```
Uma vez que peguemos o jeito podemos lidar com circuitos muito mais complexos.
"""

# ╔═╡ 25fb0825-5842-49af-96a4-a61bb25ab42b
load("circuitao.png")

# ╔═╡ 9dc1904f-0639-493a-b7c5-5cbe180f9fd6
md"""Nesse caso, sabendo que só entra corrente pelo canto inferior esquerdo e sai pelo canto superior direito, se soubermos os valores dessas correntes, podemos encontrar as voltagens em todos os nós _quando o circuito atingir o equilíbrio_ sem a necessidade de medida. Para isso temos que resolver um sistema grande com equações do tipo:
```math
(V_N + V_L + V_S + V_O) - 4V = \begin{cases}
-I & \text{se superior direito} \\
+I & \text{se inferior esquerdo} \\
0 & \text{caso contrário}
\end{cases}
```
Obs: estamos aqui usando a segunda lei de Kirchhoff.

É claro que essas equações somente são válidas paras os nós interiores. No caso da fronteira temos que tomar cuidado especial, mas não vamos nos preocupar com isso por agora. Isso será assunto do final da aula.
"""

