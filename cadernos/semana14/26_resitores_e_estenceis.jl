md"""
Como já vimos, um _offset array_ permite que você use índices além do formato padrão 1:m, 1:n. Isso é bem útil se queremos aplicar estênceis, já que podemos criar células fantasmas com índices como 0 e n + 1 ou m + 1.

Por exemplo, abaixo criamos um offset array com uma borda de células fantasmas capaz de conter a matriz `data` original no seu "interior".
"""

# ╔═╡ 5fb6e7b6-2901-11eb-0e94-aba290fd0bae
A = OffsetArray(zeros(Int, 8, 9), 0:7, 0:8)

