# ╔═╡ 66b8d093-0498-4782-8d5c-659545e61377
function count_values(n_values, rolls)
	counts = zeros(Int, n_values)
	@inbounds for i in rolls # @inbounds save time assuming valid indexes
		counts[i] += 1
	end
	return counts
end

# ╔═╡ c5f16c9e-61d6-4645-8779-e6afcc52b94d
