## Introdução

Esse caderno fala sobre _abstração_. Do ponto de vista computacional, podemos pensar em abstração como o oposto da _especialização_. Ou seja, abstração é a arte de se ver o que há de comum em objetos diferentes, focando no que importa para a tarefa do momento.

Vejamos com um exemplo meio bobo, mas elucidativo.

### O que é _um_?

Antes de tentarmos partir para os fundamentos da Matemática, deixe-me apresentar alguns objetos que podem ser vistos naturalmente como _um_ em contextos diferentes.
"""

# ╔═╡ 6fcac482-70ee-11eb-0b80-ff41c708053b
md"Cada um desses itens pode ser interpretado como o _um_ em seu contexto específico. Ou seja eles são diferentes versões de representações _especializadas_ do _um_):
1. Como um inteiro
1. Como um float (ponto flutuante)
1. Como uma string (cadeia de caracteres)
1. Como um número racional (sim, Julia tem isso!)
1. Como uma figura enfeitada do número 1
1. A matriz identidade 2x2
1. Como **um** foguete

É claro que cada um desses exemplos é apenas uma versão da ideia abstrata de _um_. Como esse é um conceito simples e fundamental, há inúmeras representações do _um_ nas várias linguagens, notações, em manifestações artísticas, etc. 

A diferença entre eles é clara. De fato nós deixamos isso claro ao descrever cada um deles como sua versão especializada. Mas para o computador, como será que ele diferencia essas diferentes formas do _um_?
"

