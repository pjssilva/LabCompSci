# ╔═╡ 423f22c0-336a-4640-bbd2-2649e6021de6
md"""
# Vizinhança: uma janela 3×3 criada com índices cartezianos

Vamos começar criando uma janela 3×3 de deslocamentos com índices cartezianos.
"""

# ╔═╡ b6fde83c-2901-11eb-0e3b-4b3766579cc8
