## Conclusão

Os desenvolvedores de Julia acreditam que linguagens de programação deveriam permitir realizar todas as operações que fazem sentido para os diferentes tipos de maneira natural. Isso porque muitas vezes a mesma operação faz sentido para diferentes tipos. Então podemos abstrair as diferenças e escrever um único código para o que esses objetos têm em comum. 

A especialização deve ser usada apenas quando estritamente necessária.
"

